  `amount` DECIMAL(10,2) DEFAULT 0,
  `shipping_fee` DECIMAL(10,2) DEFAULT 0,
  `total_amount` DECIMAL(10,2) DEFAULT 0,
  `status` VARCHAR(16) DEFAULT 'PENDING',
  `address` VARCHAR(500) DEFAULT NULL,
  `tracking_no` VARCHAR(64) DEFAULT NULL,
